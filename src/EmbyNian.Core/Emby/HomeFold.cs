namespace EmbyNian.Emby;

/// <summary>
/// 主页首屏的「矮窗档」：窗口拉矮到「继续观看」那块牌子底下那条线被第一屏裁掉之后，媒体库那一排不再占横排的格子，
/// 改压到轮播封面的左下角，原来在它下面的那一排向上补位 ——「把媒体库那压到轮播图封面的左下角，原来媒体库
/// 下方的哪一栏向上移填补媒体库的位置」（用户的话，2026-09-13）。
/// <para>
/// 触发线同一天再改过一次：**不看下一排整排出没出屏，看「继续观看」牌子底下那条通栏线** ——「窗口裁切超过继续
/// 观看下方的那条线的时候就触发媒体库上移」。线以下就是那一排的卡，线一被裁，屏上只剩一块「有招牌没货」的牌子
/// 压在窗口底上，那是这一档里最难看的一截 —— 所以线到即压，牌子自己露不露头不参与。
/// </para>
/// <para>
/// 触发线 2026-09-22 又往下挪了一排：**看「媒体库下面那一排」的再下面那一排的封面顶** ——「调整媒体库上移的
/// 阈值，改为快要显示下方媒体库封面的时候上移（上图红线的位置）」「主页没有继续观看的时候媒体库阈值也改为快要
/// 显示下方媒体库封面的时候上移」（用户的话，配一张截图：红线正压在「最近添加 · 电视节目」那一排封面的上沿）。
/// 从前那条线落在**媒体库下面那一排自己**的封面顶上，于是窗口刚裁到那一排的封面，媒体库就先一步压上了轮播 ——
/// 屏上明明还装得下第二排的封面，却先把它让掉。现在这条线再往下一排：窗口一路矮到**连再下面那一排的封面都放
/// 不下**（封面顶正要碰到窗口底）才压上；压上腾出来的那一排高，正好把这一排封面整块托进第一屏 —— 「快要显示」
/// 的就是它。改的是同一条线上的**哪一排**，两条边界（线、带子的设计形状）的形状一字未动。
/// </para>
/// <para>
/// 回默认的那一档也是同一天定的：**不看媒体库自己还在不在屏上，看轮播带还撑不撑得住设计形状** ——「轮播图上下
/// 裁切过多时隐藏，默认大小时不隐藏」。
/// </para>
/// <para>
/// 纯的、在 Core，和 <see cref="HomeCarousel"/> 同一个理由：这条界线是「哪一档窗口该用哪种摆法」的决定，
/// 输入全是量出来的几何，输出只有一个布尔 —— 正该被单测钉住的部分。屏上量这几样（那条线 ＝ 下一排的顶 ＋
/// 牌子的高，牌子多高从排好的树上量）、把媒体库搬进搬出横排的那一半在 <c>HomePage</c>（纯 UI 行为，住代码后置）。
/// </para>
/// <para>
/// 两条边界，中间是压上档的窗口高度带：
/// <list type="number">
/// <item>那条线（<paramref name="nextRowLine"/>，<see cref="CoversLine"/> 算出来的：媒体库下面那一排的**再下面
/// 那一排**的封面顶，没有第二排时退回媒体库下面那一排自己的封面顶）还在第一屏外 —— 线以下（那一排的卡）一个
/// 像素都不露，压上。媒体库自己露不露头不再参与：它整个出了屏、轮播还完好的那一档照样压着（那一档要是回
/// 默认，媒体库跟着沉到第一屏外，第一屏就真的什么都不剩了）；</item>
/// <item>视口够不到带子的设计形状（<paramref name="bandHeight"/>，<see cref="HomeCarousel.NaturalHeight"/>）
/// —— 带子被一屏压矮，剧照上下裁切开始超出默认大小那一档（一边约 12%），该回默认了。默认大小裁多少就是
/// 多少，所以「过多」不用再去挑一个百分比：超出设计形状的第一像素就是那道线。</item>
/// </list>
/// </para>
/// </summary>
public static class HomeFold
{
    /// <summary>
    /// 这一档窗口该不该把媒体库那一排压上轮播。
    /// <para>
    /// <paramref name="nextRowLine"/> 是**滚回顶上之后**那条线到视口顶边的距离（内容坐标，不带滚动位移，按默认
    /// 摆法的几何还原）—— 拿现场坐标来判，用户往下滚一下这一档就会自己翻面。这条线由 <see cref="CoversLine"/>
    /// 算：压上档里横排媒体库那个位置站着补位的下一排，把它当作回到媒体库的格子算，再往下一排就是那条线所在的
    /// 一排 —— 牌子和空当页面从排好的树上量，这里不写死。
    /// </para>
    /// </summary>
    /// <param name="viewport">第一屏的高（窗口客户区）。</param>
    /// <param name="nextRowLine">那条线在第一屏里的位置（默认摆法的几何），见 <see cref="CoversLine"/>。</param>
    /// <param name="bandHeight">轮播带按设计形状的高（<see cref="HomeCarousel.NaturalHeight"/>，不被一屏封住）。</param>
    public static bool LibraryOnBanner(double viewport, double nextRowLine, double bandHeight)
    {
        if (viewport <= 0) return false;

        // 那条线压着第一屏底或更靠下（线以下全被裁），并且视口还撑得住带子的设计形状（剧照上下裁切没超出默认档）。
        return nextRowLine >= viewport && viewport >= bandHeight;
    }

    /// <summary>
    /// 那条线在哪儿：**媒体库下面那一排的「再下面那一排」的封面顶**（用户的话，2026-09-22，见类型开头那一段）。
    /// <para>
    /// 输入是「媒体库下面那一排」（＝压上档里补上媒体库那一格的那一排）在**默认摆法**里的几何：它的顶、它的
    /// 牌子有多高、牌子到排卡之间那道空当、它的排卡有多高（封面 ＋ 卡底那两行字，<c>CardShelf.RowHeight</c>），
    /// 加上排与排之间的空当。这一排自己的封面顶 ＝ 顶 ＋ 牌子 ＋ 空当；再往下一排要去掉这一排的整整一排（牌子 ＋
    /// 空当 ＋ 排卡）加一道排间空当、再加上自己那份「牌子 ＋ 空当」—— 两处用的是同一张牌子、同一个空当、同一个
    /// 排间空当，页面量一份递进来就够，这里不写第二份（2026-09-18 那场「矮窗档来回翻」就是同一条线在两个方向各
    /// 算了一遍、算出了两个答案）。
    /// </para>
    /// <para>
    /// <paramref name="hasBelow"/> 是这一排下面还有没有别的排：没有（媒体库下面只有这一排）时交回这一排自己的
    /// 封面顶 —— 那一档压上腾出的位置只够把这一排托进第一屏，界线的语义原样不变。
    /// </para>
    /// </summary>
    /// <param name="rowTop">那一排在默认摆法里的顶（内容坐标）。</param>
    /// <param name="headHeight">一排牌子有多高。</param>
    /// <param name="headGap">牌子到排卡之间那道空当。</param>
    /// <param name="cardHeight">那一排的排卡有多高（封面 ＋ 卡底那两行字）。</param>
    /// <param name="rowGap">排与排之间的空当。</param>
    /// <param name="hasBelow">那一排下面还有没有别的排。</param>
    public static double CoversLine(
        double rowTop,
        double headHeight,
        double headGap,
        double cardHeight,
        double rowGap,
        bool hasBelow)
    {
        var reach = headHeight + headGap;                       // 这一排：牌子 ＋ 空当
        var covers = rowTop + reach;                            // 这一排自己的封面顶

        return hasBelow
            ? covers + reach + cardHeight + rowGap              // 再下面那一排的封面顶
            : covers;
    }
}
